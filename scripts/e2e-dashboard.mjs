// Screenshots of every dashboard screen: node scripts/e2e-dashboard.mjs <host> <email> <password> <licenseId>
import { chromium } from 'playwright';
const [base, email, password, lic] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error' && !/GL Driver|Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(base + '/login'); await page.waitForTimeout(600);
await page.screenshot({ path: 'tmp/d-0-login.png' });
await page.fill('input[type=email]', email); await page.fill('input[type=password]', password); await page.click('button.primary');
await page.waitForURL(base + '/'); await page.waitForTimeout(900);
const shot = async (name, url, wait = 900, full = false) => { if (url) await page.goto(base + url); await page.waitForTimeout(wait); await page.screenshot({ path: `tmp/d-${name}.png`, fullPage: full }); };
await shot('1-overview', null);
await shot('2-store', '/store');
await shot('3-games', '/games');
await shot('4-customize', `/games/${lic}/customize`, 6000);
await page.click('.snav button:has-text("Scene art")'); await page.waitForTimeout(800); await page.screenshot({ path: 'tmp/d-5-assets.png' });
await page.click('.snav button:has-text("Rules")'); await page.waitForTimeout(800); await page.screenshot({ path: 'tmp/d-6-rules.png', fullPage: true });
await shot('7-integrate', `/games/${lic}/integrate`, 900, true);
await shot('8-players', `/games/${lic}/players`, 1200, true);
await shot('9-settings', `/games/${lic}/settings`);
await page.setViewportSize({ width: 390, height: 844 }); await shot('10-mobile', `/games/${lic}/customize`, 1500);
await page.evaluate(() => (document.documentElement.dataset.theme = 'dark')); await page.setViewportSize({ width: 1440, height: 900 }); await shot('11-dark', '/games', 1000);
console.log(errors.length ? 'ERRORS: ' + errors.slice(0, 5).join(' | ') : 'no console errors');
await browser.close();
