import { chromium } from 'playwright';
import fs from 'node:fs';
const seed = JSON.parse(fs.readFileSync('tmp/seed2.json', 'utf8'));
const base = 'http://localhost:3000';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
page.on('pageerror', e => console.log('[pageerror]', e.message));
page.on('console', m => { if (m.type() === 'error' && !/GL Driver/.test(m.text())) console.log('[console.error]', m.text().slice(0, 200)); });
await page.goto(base + '/login');
await page.fill('input[type=email]', seed.buyerEmail);
await page.fill('input[type=password]', seed.buyerPassword);
await page.click('button.primary');
await page.waitForURL(base + '/');
await page.waitForTimeout(800);
await page.screenshot({ path: 'tmp/dash-1-store.png' });
await page.goto(base + '/games'); await page.waitForTimeout(800);
await page.screenshot({ path: 'tmp/dash-2-mygames.png' });
const slots = seed.games.find(g => g.game === 'lucky-77');
await page.goto(`${base}/games/${slots.licenseId}/customize`); await page.waitForTimeout(9000);
await page.screenshot({ path: 'tmp/dash-3-customize.png' });
await page.goto(`${base}/games/${slots.licenseId}/integrate`); await page.waitForTimeout(1200);
await page.screenshot({ path: 'tmp/dash-4-integrate.png', fullPage: true });
const spin = seed.games[0];
await page.goto(`${base}/games/${spin.licenseId}/players`); await page.waitForTimeout(1500);
await page.screenshot({ path: 'tmp/dash-5-players.png', fullPage: true });
await browser.close();
